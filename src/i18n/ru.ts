// A piece of an alkali metal: its size, and what happens when it is too big for the vessel.
function piece(p: Record<string, string>, h: H, t: EventText): EventText {
  const size = p.mm && p.mm !== '0' ? ` Кусочек ${h.num(Number(p.g))} г — это примерно кубик ${p.mm} мм.` : '';
  const violent = p.violent ? ' Металла слишком много для такого сосуда: вода вскипает, и горячую щёлочь выбрасывает наружу — часть раствора выплеснулась.' : '';
  return { ...t, title: p.violent ? `${h.cap(h.metal(p.metal))} реагирует слишком бурно` : t.title, say: t.say + violent + size };
}

